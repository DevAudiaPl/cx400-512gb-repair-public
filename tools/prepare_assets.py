#!/usr/bin/env python3
"""Reproduce checked recovery assets from local vendor files; no device access."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
INPUT_SHA = {
    'updater': '1e071b93ec8e629d9bdb6b7222432594a998afcc09df6e9fbea843227e384a93',
    'burner': '440c6246d332826ffc2a8ca4411e48bd78bded67c36e194b912f6c71f89eeb55',
    'mp_api': '87a3455e5cfc41de3c65854f17bd47ce8b42dbefbf4d9f43e67a8e38ca2f8455',
}

def sha(data):
    return hashlib.sha256(data).hexdigest()

def require(ok, message):
    if not ok:
        raise RuntimeError(message)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ('updater', 'burner', 'mp-api', 'psychite', 'output'):
        parser.add_argument('--' + flag, type=Path, required=True)
    args = parser.parse_args()
    values = {}
    for name, expected in INPUT_SHA.items():
        path = getattr(args, name)
        require(path.is_file(), 'Input missing: ' + name)
        values[name] = path.read_bytes()
        require(sha(values[name]) == expected, 'Wrong vendor input SHA: ' + name)
    dependency = args.psychite.resolve()
    if (dependency / 'src/phison_s11/firmware.py').is_file():
        dependency = dependency / 'src'
    require((dependency / 'phison_s11/firmware.py').is_file(), 'Psychite checkout not found')
    sys.path.insert(0, str(dependency))
    from phison_s11 import algorithm, firmware

    source = ROOT / 'scripts/recovery-v2'
    files = {p.name: p.read_bytes() for p in source.iterdir() if p.is_file()}
    exe = values['updater']
    container = exe[1708784:1708784 + 512 + 757760 + 786432]
    normal = firmware.Firmware.from_bytes(container)
    require(str(normal.version) == 'SBFM61.3', 'Unexpected normal firmware')
    files['normal-SBFM61.3.bin'] = container[512 + 757760:]
    for i, section in enumerate(normal.normal_code.sections):
        if section is not None:
            files[f'normal-section{i}.bin'] = bytes(section.code)

    burner = firmware.Firmware.from_bytes(values['burner']).burner_code
    for i, section in enumerate(burner.iram_sections):
        files[f'iram-section{i}.bin'] = bytes(section.code)
    files['sram-xor.bin'] = burner.sram_section_crypt
    # Audited raw offsets/addresses in the exact checked updater and MP_API.
    def updater_data(address, size):
        offset = 0x18d800 + address - 0x58f000
        return exe[offset:offset + size]
    files['infoblock-template.bin'] = updater_data(0x597520, 512)
    files['smart-template.bin'] = updater_data(0x5964c0, 176).ljust(512, b'\0')
    files['regression-xor0561.bin'] = algorithm.cipher_xor_0561(bytes(16384))
    sram = bytes(x ^ 255 for x in files['sram-xor.bin'])
    files['erase09-burner-guard.bin'] = sram[0x60015484 - 0x60000400:0x600154a9 - 0x60000400]
    offset = 0x400 + 0x10073497 - 0x10001000
    files['erase09-host-frame.bin'] = values['mp_api'][offset:offset + 0x4f]

    require(sha(files['assets.json']) == '8ab703418cb74103cbb77495d69ea3f90c40499bad6f40fd7a048bde126b0168',
            'Original assets manifest changed')
    meta = json.loads(files['assets.json'])
    for name, expected in meta['files'].items():
        require(name in files, 'Required generated asset missing: ' + name)
        data = files[name]
        require(len(data) == expected['size'] and sha(data) == expected['sha256'],
                'Generated bytes do not match the tested asset: ' + name)
    output = args.output.resolve()
    require(output != source.resolve(), 'Use a separate working directory')
    for name, data in files.items():
        destination = output / name
        require(not destination.exists() or destination.read_bytes() == data,
                'Existing different output file: ' + name)
    output.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        destination = output / name
        if not destination.exists():
            destination.write_bytes(data)
    print(json.dumps({'result': 'ASSETS_MATCH_ORIGINAL', 'assets_checked': len(meta['files']),
                      'files': len(files), 'hardware_access': False}, indent=2))

if __name__ == '__main__':
    main()
